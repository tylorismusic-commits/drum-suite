#!/usr/bin/env python3
"""Convert Slate Trigger 2 .TCI instruments to SFZ + WAV.

This is a standalone tool.  It uses the MIT-licensed clean-room decoder from
https://github.com/AidanScroggins/tci2wav (vendored under vendor/) and writes
one SFZ instrument per TCI, with velocity layers and round robins.

TCI is a proprietary Slate/Trigger format.  Only use this with files you are
licensed to use.  The decoder is unofficial and unsupported by Slate.

Usage:
  python3 tci2sfz.py input.tci [-o output-dir] [--name Family] [--mic Z3]
  python3 tci2sfz.py library-dir -o output-dir --bank

The output layout is:
  <out>/<family>/<mic>/instrument.sfz
  <out>/<family>/<mic>/samples/*.wav
  <out>/<family>/<mic>/README.txt
"""

import argparse
import os
import re
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
VENDOR = os.path.join(HERE, "vendor")
sys.path.insert(0, VENDOR)

try:
    import tci_export  # noqa: E402
except Exception as exc:  # pragma: no cover - friendly CLI error
    sys.exit(
        "Could not load the TCI decoder (numpy is required):\n"
        f"  {exc}\n"
        "Install it with: python3 -m pip install numpy"
    )


def note_name(note):
    names = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
    note = max(0, min(127, int(note)))
    return f"{names[note % 12]}{note // 12 - 1}"


def parse_layer(filename):
    m = re.search(r"_V(\d+)_RR(\d+)\.wav$", filename, re.IGNORECASE)
    if not m:
        return 1, 1
    return int(m.group(1)), int(m.group(2))


def convert_one(tci_path, out_root, family, mic, verbose=True):
    family = family or os.path.splitext(os.path.basename(tci_path))[0]
    family = re.sub(r"[^A-Za-z0-9._-]+", "_", family).strip("_") or "Instrument"
    mic = re.sub(r"[^A-Za-z0-9._-]+", "_", mic or "MIC").strip("_") or "MIC"
    dest = os.path.join(out_root, family, mic)
    wav_dir = os.path.join(dest, "samples")
    os.makedirs(wav_dir, exist_ok=True)

    # Decode into a temporary folder first, then move only the WAVs we keep.
    with tempfile.TemporaryDirectory(prefix="tci2sfz-") as tmp:
        try:
            exported = tci_export.export_tci(tci_path, tmp, family, mic)
        except Exception as exc:
            if verbose:
                print(f"  failed: {exc}", file=sys.stderr)
            return False
        wavs = [name for name, _grade, _note in exported
                if name.lower().endswith(".wav")]
        if not wavs:
            if verbose:
                print("  no decodable waves", file=sys.stderr)
            return False
        layers = {}
        for name in wavs:
            v, rr = parse_layer(name)
            layers.setdefault(v, []).append((rr, name))
        max_v = max(layers)
        lines = [
            "// Generated by tci2sfz from a Slate Trigger TCI",
            f"// Source: {os.path.basename(tci_path)}",
            f"// Family: {family}   Mic: {mic}",
            "<control> default_path=samples",
            "<global> loop_mode=one_shot",
            "",
        ]
        for v in sorted(layers):
            entries = sorted(layers[v])
            max_rr = max(rr for rr, _ in entries)
            lovel = int((v - 1) * 128 / max_v)
            hivel = int(v * 128 / max_v) - 1
            lovel = max(0, min(127, lovel))
            hivel = max(lovel, min(127, hivel))
            lines.append(
                f"<group> lovel={lovel} hivel={hivel} "
                f"seq_length={max(1, max_rr)}"
            )
            for rr, name in entries:
                lines.append(
                    f"<region> sample={name} seq_position={max(1, rr)}"
                )
            lines.append("")
        sfz_path = os.path.join(dest, "instrument.sfz")
        with open(sfz_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        for _, name in [(rr, name) for v in layers for rr, name in layers[v]]:
            shutil.move(os.path.join(tmp, name), os.path.join(wav_dir, name))
        if os.path.exists(os.path.join(tmp, "MAP.txt")):
            shutil.copy2(os.path.join(tmp, "MAP.txt"), dest)

    with open(os.path.join(dest, "README.txt"), "w", encoding="utf-8") as f:
        f.write(
            "Generated by tci2sfz.\n\n"
            f"TCI: {os.path.basename(tci_path)}\n"
            f"Family: {family}\nMic: {mic}\n"
            f"Velocity layers: {len(layers)}\n"
            f"Waves: {sum(len(v) for v in layers.values())}\n\n"
            "Load instrument.sfz in Drum Suite and select the MIDI note for\n"
            "this drum (the default follows the drum tab).\n\n"
            "TCI is a proprietary Slate/Trigger format. The decoder is an\n"
            "unofficial clean-room implementation; only use it with files you\n"
            "are licensed to use. Stereo TCI attacks may be missing the first\n"
            "~2 ms because that part of the format is still undecoded.\n"
        )
    if verbose:
        print(f"  -> {sfz_path}")
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", help="a .tci file or a folder (with --bank)")
    ap.add_argument("-o", "--out", default="tci-sfz", help="output folder")
    ap.add_argument("--name", default="", help="family name for a single file")
    ap.add_argument("--mic", default="", help="mic label for a single file")
    ap.add_argument("--bank", action="store_true",
                    help="recursively convert every .tci under input")
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)
    if args.bank:
        if not os.path.isdir(args.input):
            sys.exit("--bank needs a folder")
        jobs = []
        for root, _dirs, files in os.walk(args.input):
            for name in sorted(files):
                if name.lower().endswith(".tci"):
                    jobs.append(os.path.join(root, name))
        print(f"{len(jobs)} TCI file(s) -> {args.out}")
        ok = 0
        for path in jobs:
            print(f"--- {os.path.relpath(path, args.input)}")
            mic = os.path.splitext(os.path.basename(path))[0].split()[-1]
            family = os.path.basename(os.path.dirname(path)) or \
                os.path.splitext(os.path.basename(path))[0]
            if convert_one(path, args.out, family, mic):
                ok += 1
        print(f"done: {ok}/{len(jobs)} converted")
    else:
        if not os.path.isfile(args.input):
            sys.exit("input .tci not found")
        print(f"--- {os.path.basename(args.input)}")
        mic = args.mic or os.path.splitext(os.path.basename(args.input))[0].split()[-1]
        if not convert_one(args.input, args.out, args.name, mic):
            sys.exit(1)


if __name__ == "__main__":
    main()
